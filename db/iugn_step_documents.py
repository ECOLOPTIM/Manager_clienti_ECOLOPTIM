"""Audited work/step attachments; files and milestone confirmation commit together."""
from contextlib import closing
from datetime import date, datetime, timezone
import hashlib
import mimetypes
from pathlib import Path
import secrets
from db import db, permissions, iugn, iugn_documents as issued
from config.iugn_step_documents import KINDS, REQUIRED_KINDS


def migrate(conn):
    identity = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if db.DATABASE_URL else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    conn.execute(f'''CREATE TABLE IF NOT EXISTS iugn_step_documents (
        id {identity}, lucrare_id INTEGER NOT NULL REFERENCES lucrari(id) ON DELETE CASCADE,
        step_key TEXT NOT NULL, kind TEXT NOT NULL, filename TEXT NOT NULL,
        path TEXT NOT NULL UNIQUE, sha256 TEXT NOT NULL, uploaded_by TEXT NOT NULL,
        uploaded_at TEXT NOT NULL, document_date TEXT NOT NULL, reference TEXT NOT NULL,
        UNIQUE(lucrare_id, step_key, kind, sha256))''')


def list_for_work(lid):
    permissions.require('read')
    with closing(db._connect()) as conn:
        iugn._work(conn, lid)
        cur=conn.cursor()
        db._execute(cur,'SELECT * FROM iugn_step_documents WHERE lucrare_id=? ORDER BY id DESC',(int(lid),))
        rows=[dict(zip([c[0] for c in cur.description], row)) for row in cur.fetchall()]
        # Issued originals remain immutable and are never replaced by signed copies.
        for table,label,kind in (('iugn_contract_issues','Contract emis','contract_emis'),
                                  ('iugn_mandate_issues','Mandat emis','mandat_emis')):
            row=issued._row(conn,f'SELECT * FROM {table} WHERE lucrare_id=?',(int(lid),))
            if row:
                rows.append(dict(row,step_key='contract_emis',kind=kind,label=label,
                                 origin=table,uploaded_at=row['issued_at'],reference=row['number']))
        return rows


def download(lid, origin, document_id):
    permissions.require('read')
    with closing(db._connect()) as conn:
        iugn._work(conn,lid)
        if origin=='uploaded':
            row=issued._row(conn,'SELECT * FROM iugn_step_documents WHERE lucrare_id=? AND id=?',(int(lid),int(document_id)))
        elif origin in ('iugn_contract_issues','iugn_mandate_issues'):
            row=issued._row(conn,f'SELECT * FROM {origin} WHERE lucrare_id=?',(int(lid),))
        else:raise ValueError('Sursa documentului este invalida.')
    if not row:raise ValueError('Documentul nu apartine acestei lucrari.')
    path=Path(row['path'])
    if not path.resolve().is_relative_to(Path(db.UPLOAD_DIR).resolve()):
        raise ValueError('Documentul nu se afla in arhiva configurata.')
    try:data=path.read_bytes()
    except FileNotFoundError:raise ValueError('Documentul lipseste din arhiva. Verifica backupul.') from None
    if hashlib.sha256(data).hexdigest()!=row['sha256']:
        raise ValueError('Documentul a fost modificat in afara aplicatiei. Verifica arhiva.')
    return data,row['filename'],mimetypes.guess_type(row['filename'])[0] or 'application/octet-stream'


def _cleanup(paths):
    for path in paths:
        try:
            with closing(db._connect()) as conn:
                saved=issued._row(conn,'SELECT id FROM iugn_step_documents WHERE path=?',(str(path),))
            if not saved:path.unlink(missing_ok=True)
        except Exception:pass  # An ambiguous commit requires reconciliation, never deleting evidence.


def upload(lid, step_key, kind, files, *, expected_revision, occurred_on,
           confirm=False, reference='', note='', scheduled_for='', team=''):
    permissions.require('write')
    if step_key not in KINDS or kind not in KINDS[step_key]:
        raise ValueError('Tipul documentului nu corespunde etapei.')
    if not files or len(files)>20:raise ValueError('Alege intre 1 si 20 de fisiere.')
    day=date.fromisoformat(str(occurred_on))
    if day>date.today():raise ValueError('Data documentului nu poate fi in viitor.')
    checked=[]
    for filename,data in files:
        name=db._sanitize_filename(filename)
        if not isinstance(data,bytes) or not data:raise ValueError('Fisierul este gol.')
        if len(data)>db.MAX_UPLOAD_BYTES:raise ValueError('Fisierul depaseste limita pentru atasamente.')
        checked.append((name,data,hashlib.sha256(data).hexdigest()))
    journal=[]
    try:
        with closing(db._connect()) as conn,conn:
            if not db.DATABASE_URL:conn.execute('BEGIN IMMEDIATE')
            _,work=issued._records(conn,int(lid),True)
            state=iugn._checked_load(conn,int(lid),expected_revision)
            if not iugn.can_record(state,step_key):
                raise PermissionError('Incarcarea necesita persoana desemnata pentru aceasta etapa.')
            if step_key=='contract_semnat' and not iugn.contract_document_registered(conn,lid):
                raise ValueError('Emite mai intai contractul din aplicatie.')
            if kind=='mandat_semnat' and not issued._row(conn,'SELECT number FROM iugn_mandate_issues WHERE lucrare_id=?',(int(lid),)):
                raise ValueError('Emite mai intai mandatul din aplicatie.')
            directory=Path(db.UPLOAD_DIR)/str(work['client_id']);directory.mkdir(parents=True,exist_ok=True)
            now=datetime.now(timezone.utc).isoformat();actor=iugn._actor()
            cur=conn.cursor()
            for filename,data,digest in checked:
                if issued._row(conn,'SELECT id FROM iugn_step_documents WHERE lucrare_id=? AND step_key=? AND kind=? AND sha256=?',(int(lid),step_key,kind,digest)):
                    raise ValueError('Acest document este deja incarcat la etapa respectiva.')
                path=directory/f'IUGN-L{int(lid)}-{secrets.token_hex(8)}-{filename}'
                with path.open('xb') as out:
                    journal.append(path);out.write(data)
                db._execute(cur,'''INSERT INTO iugn_step_documents
                    (lucrare_id,step_key,kind,filename,path,sha256,uploaded_by,uploaded_at,document_date,reference)
                    VALUES (?,?,?,?,?,?,?,?,?,?)''',
                    (int(lid),step_key,kind,filename,str(path),digest,actor,now,day.isoformat(),str(reference).strip()))
                db._execute(cur,'''INSERT INTO atasamente
                    (client_id,filename,path,uploaded_by,upload_date,lucrare_id,sarcina_id)
                    VALUES (?,?,?,?,?,?,NULL)''',(work['client_id'],path.name,str(path),actor,now,int(lid)))
            # A signed mandate must never stand in for the signed service contract.
            may_confirm=confirm and step_key not in state['facts'] and not (step_key=='contract_semnat' and kind=='mandat_semnat')
            if may_confirm:
                db._execute(cur,'SELECT DISTINCT kind FROM iugn_step_documents WHERE lucrare_id=? AND step_key=?',(int(lid),step_key))
                missing=REQUIRED_KINDS.get(step_key,set())-{row[0] for row in cur.fetchall()}
                if missing:
                    labels=', '.join(KINDS[step_key][k] for k in sorted(missing))
                    raise ValueError('Pentru confirmare mai trebuie: '+labels+'. Salveaza documentul fara confirmare sau adauga fisierele lipsa.')
                evidence='; '.join(name for name,_,_ in checked)
                text=' | '.join(x for x in (str(note).strip(),str(reference).strip(),'Documente: '+evidence) if x)
                iugn.record_event_in_transaction(conn,int(lid),step_key,day.isoformat(),
                    expected_revision=expected_revision,note=text,scheduled_for=scheduled_for,team=team)
            else:
                iugn._save(conn,int(lid),expected_revision,state,'document_incarcat',day.isoformat(),
                    {'step':step_key,'kind':kind,'files':[n for n,_,_ in checked],'reference':str(reference).strip(),'note':str(note).strip()})
        return {'confirmed':may_confirm,'count':len(checked)}
    except BaseException:
        _cleanup(journal);raise
