-- PostgreSQL test schema v1. No SQLite data is imported.

CREATE TABLE utilizatori (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    parola TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'birou',
    activ INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 0,
    created_at TEXT
);

CREATE TABLE clienti (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume TEXT,
    email TEXT,
    telefon TEXT,
    firma TEXT,
    status TEXT,
    observatii TEXT,
    data_adaugarii TEXT,
    cod_intern TEXT,
    scor INTEGER,
    remark TEXT,
    domiciliu_judet TEXT,
    domiciliu_localitate TEXT,
    domiciliu_strada TEXT,
    domiciliu_numar TEXT,
    domiciliu_bloc TEXT,
    domiciliu_apartament TEXT,
    consum_judet TEXT,
    consum_localitate TEXT,
    consum_strada TEXT,
    consum_numar TEXT,
    consum_bloc TEXT,
    consum_apartament TEXT,
    cnp TEXT,
    ci_serie TEXT,
    ci_numar TEXT,
    ci_emitent TEXT,
    ci_data TEXT,
    domiciliu_scara TEXT,
    domiciliu_etaj TEXT
);

CREATE TABLE lucrari (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER,
    tip_lucrare TEXT,
    valoare_contractata NUMERIC(14,2),
    responsabil TEXT,
    status TEXT,
    data_contract TEXT,
    data_programare TEXT,
    observatii TEXT,
    descriere TEXT,
    adresa_judet TEXT,
    adresa_localitate TEXT,
    adresa_strada TEXT,
    revision INTEGER NOT NULL DEFAULT 0,
    adresa_numar TEXT,
    adresa_bloc TEXT,
    adresa_apartament TEXT,
    interval_orar TEXT,
    echipa TEXT,
    sef_echipa TEXT,
    avans NUMERIC(14,2),
    cod_atr TEXT,
    executant TEXT,
    element_sda TEXT,
    comanda_aprovizionare TEXT,
    diriginte_santier TEXT,
    contract_prestari_servicii TEXT,
    numar_conventie_tehnica TEXT,
    data_programare_pif TEXT,
    interval_orar_pif TEXT,
    echipa_pif TEXT,
    sef_echipa_pif TEXT
);

CREATE TABLE atasamente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    filename TEXT NOT NULL,
    path TEXT NOT NULL,
    uploaded_by TEXT,
    upload_date TEXT,
    lucrare_id INTEGER,
    sarcina_id INTEGER
);

CREATE TABLE facturi (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    numar TEXT,
    data_emiterii TEXT,
    data_scadenta TEXT,
    total NUMERIC(14,2) NOT NULL DEFAULT 0,
    moneda TEXT NOT NULL DEFAULT 'RON',
    status TEXT NOT NULL DEFAULT 'NEINCASATA',
    observatii TEXT,
    created_at TEXT,
    created_by TEXT
);

CREATE TABLE plati (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    factura_id INTEGER NOT NULL,
    data_platii TEXT,
    suma NUMERIC(14,2) NOT NULL DEFAULT 0,
    metoda TEXT,
    observatii TEXT,
    created_at TEXT,
    created_by TEXT
);

CREATE TABLE documente_seq (
    an INTEGER PRIMARY KEY,
    last_os INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE contracte_seq (
    an INTEGER PRIMARY KEY,
    last_ctr INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE registru_seq_client (
    client_id INTEGER PRIMARY KEY,
    last_nr INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE sarcini (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    lucrare_id INTEGER NOT NULL,
    tip_sarcina TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'NOU',
    responsabil TEXT,
    data_scadenta TEXT,
    observatii TEXT,
    created_at TEXT,
    created_by TEXT,
    closed_at TEXT,
    ordine INTEGER
);

CREATE TABLE inregistrari (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    lucrare_id INTEGER NOT NULL,
    sarcina_id INTEGER,
    nr_inregistrare TEXT NOT NULL,
    data TEXT,
    descriere TEXT,
    created_at TEXT,
    created_by TEXT
);

-- Keep ownership and referential consistency in the database as well as the UI.
ALTER TABLE utilizatori ADD CONSTRAINT utilizatori_username_key UNIQUE (username);
ALTER TABLE lucrari ALTER COLUMN client_id SET NOT NULL;
ALTER TABLE lucrari ADD CONSTRAINT lucrari_owner_key UNIQUE (id, client_id);
ALTER TABLE lucrari ADD FOREIGN KEY (client_id) REFERENCES clienti(id);
ALTER TABLE lucrari ADD CHECK (revision >= 0);
ALTER TABLE lucrari ADD CHECK (valoare_contractata >= 0 AND valoare_contractata < 'Infinity'::numeric);
ALTER TABLE lucrari ADD CHECK (avans >= 0 AND avans <= valoare_contractata);
ALTER TABLE facturi ADD CONSTRAINT facturi_owner_key UNIQUE (id, client_id);
ALTER TABLE facturi ADD FOREIGN KEY (client_id) REFERENCES clienti(id);
ALTER TABLE facturi ADD CHECK (total > 0 AND total < 'Infinity'::numeric);
ALTER TABLE plati ADD FOREIGN KEY (factura_id, client_id) REFERENCES facturi(id, client_id);
ALTER TABLE plati ADD CHECK (suma > 0 AND suma < 'Infinity'::numeric);
ALTER TABLE sarcini ADD CONSTRAINT sarcini_owner_key UNIQUE (id, lucrare_id, client_id);
ALTER TABLE sarcini ADD FOREIGN KEY (lucrare_id, client_id) REFERENCES lucrari(id, client_id);
ALTER TABLE inregistrari ADD FOREIGN KEY (lucrare_id, client_id) REFERENCES lucrari(id, client_id);
ALTER TABLE inregistrari ADD FOREIGN KEY (sarcina_id, lucrare_id, client_id)
    REFERENCES sarcini(id, lucrare_id, client_id);
ALTER TABLE atasamente ADD FOREIGN KEY (client_id) REFERENCES clienti(id);
ALTER TABLE atasamente ADD FOREIGN KEY (lucrare_id, client_id) REFERENCES lucrari(id, client_id);
ALTER TABLE atasamente ADD FOREIGN KEY (sarcina_id, lucrare_id, client_id)
    REFERENCES sarcini(id, lucrare_id, client_id);
ALTER TABLE atasamente ADD CHECK (sarcina_id IS NULL OR lucrare_id IS NOT NULL);
ALTER TABLE registru_seq_client ADD FOREIGN KEY (client_id) REFERENCES clienti(id);
CREATE INDEX lucrari_client_idx ON lucrari(client_id);
CREATE INDEX facturi_client_idx ON facturi(client_id);
CREATE INDEX plati_factura_idx ON plati(factura_id);
CREATE INDEX sarcini_lucrare_idx ON sarcini(lucrare_id);
CREATE INDEX inregistrari_lucrare_idx ON inregistrari(lucrare_id);
CREATE INDEX atasamente_lucrare_idx ON atasamente(lucrare_id);
