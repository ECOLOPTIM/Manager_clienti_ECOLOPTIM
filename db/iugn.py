"""Transactional IUGN persistence; additive tables and preserved legacy tasks."""
from contextlib import closing
from datetime import date, datetime, timezone
import json
import os

from db import permissions
from db import iugn_rules as rules


class WorkflowConflict(ValueError):
    pass


def migrate(conn):
    from db import db
    cur = conn.cursor()
    if db.DATABASE_URL:
        cur.execute('ALTER TABLE sarcini ADD COLUMN IF NOT EXISTS cod_flux TEXT')
        identity = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    else:
        db._add_column_if_missing(conn, 'sarcini', 'cod_flux', 'TEXT')
        identity = 'INTEGER PRIMARY KEY AUTOINCREMENT'
    cur.execute('''CREATE TABLE IF NOT EXISTS iugn_flux (
        lucrare_id INTEGER PRIMARY KEY REFERENCES lucrari(id),
        revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
        payload TEXT NOT NULL)''')
    cur.execute(f'''CREATE TABLE IF NOT EXISTS iugn_evenimente (
        id {identity},
        lucrare_id INTEGER NOT NULL REFERENCES iugn_flux(lucrare_id),
        revision INTEGER NOT NULL,
        event_key TEXT NOT NULL,
        occurred_on TEXT NOT NULL,
        recorded_at TEXT NOT NULL,
        actor TEXT NOT NULL,
        detail TEXT NOT NULL,
        UNIQUE(lucrare_id, revision))''')
    cur.execute('CREATE UNIQUE INDEX IF NOT EXISTS sarcini_cod_flux_key ON sarcini(lucrare_id, cod_flux)')


def _actor():
    return permissions.actor_username() or 'mentenanta locala'


def is_manager():
    """One explicit account, not every user who happens to have admin privileges."""
    username = permissions.actor_username()
    if username is None:
        return True  # Same trusted offline-maintenance convention as the existing DB API.
    try:
        permissions.require('admin')
    except PermissionError:
        return False
    return username == os.getenv('IUGN_MANAGER_USERNAME', 'admin')


def require_manager():
    permissions.require('write')
    if not is_manager():
        raise PermissionError('Operatia necesita contul de coordonare al lui Gelu.')


def can_record(state, key):
    permissions.require('write')
    if key in ('exceptie_contract', 'exceptie_avans', 'executie_programata', 'echipa_pif_alocata', 'reprogramare_executie'):
        return is_manager()
    role = rules.BY_KEY[key][3] if key in rules.BY_KEY else 'responsabil'
    owner = state['roles'].get(role, '')
    if key == 'executie_fara_proiect':
        # Gelu is not a substitute for the designated responsible person's decision.
        return permissions.actor_username() is None or permissions.actor_username() == owner
    return is_manager() or not owner or permissions.actor_username() == owner


def _dump(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def _work(conn, lid):
    from db import db
    cur = conn.cursor()
    db._execute(cur, 'SELECT client_id, tip_lucrare FROM lucrari WHERE id=?', (int(lid),))
    work = cur.fetchone()
    if not work or work[1] != rules.WORK_TYPE:
        raise ValueError('Fluxul IUGN este disponibil numai pentru instalatia de utilizare noua.')
    return work


def _load(conn, lid):
    from db import db
    cur = conn.cursor()
    db._execute(cur, 'SELECT revision, payload FROM iugn_flux WHERE lucrare_id=?', (int(lid),))
    row = cur.fetchone()
    if row is None:
        raise ValueError('Activeaza mai intai fluxul IUGN al lucrarii.')
    return {'revision': row[0], 'state': json.loads(row[1])}


def get(lid):
    from db import db
    with closing(db._connect()) as conn, conn:
        _work(conn, lid)
        cur = conn.cursor()
        db._execute(cur, 'SELECT revision, payload FROM iugn_flux WHERE lucrare_id=?', (int(lid),))
        row = cur.fetchone()
        if row is None:
            return None
        return {'revision': row[0], 'state': json.loads(row[1])}


def _sync_tasks(conn, lid, client_id, state):
    from db import db
    cur = conn.cursor()
    now = datetime.now(timezone.utc).isoformat()
    for index, (key, label, stream, role, _) in enumerate(rules.STEPS, 1):
        status = ('FINALIZAT' if key in state['facts'] else
                  'BLOCAT' if rules.blocked_reason(state, key) else 'NOU')
        owner = os.getenv('IUGN_MANAGER_USERNAME', 'admin') if role == 'manager' else state['roles'].get(role, '')
        db._execute(cur, '''INSERT INTO sarcini
            (client_id, lucrare_id, tip_sarcina, status, responsabil, created_at, created_by, ordine, cod_flux)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(lucrare_id, cod_flux) DO NOTHING''',
            (client_id, int(lid), label, status, owner, now, _actor(), index, key))
        fact = state['facts'].get(key, {})
        db._execute(cur, '''UPDATE sarcini SET status=?, responsabil=?, closed_at=?, observatii=?
            WHERE lucrare_id=? AND cod_flux=?''',
            (status, owner, fact.get('date'), fact.get('note', '') if key in state['facts']
             else rules.blocked_reason(state, key), int(lid), key))


def _initialize(conn, lid, client_id):
    from db import db
    state = rules.initial_state()
    cur = conn.cursor()
    db._execute(cur, '''INSERT INTO iugn_flux(lucrare_id, revision, payload)
        VALUES (?, 0, ?) ON CONFLICT(lucrare_id) DO NOTHING''', (int(lid), _dump(state)))
    if cur.rowcount == 1:
        _sync_tasks(conn, lid, client_id, state)
        _audit(conn, lid, 0, 'activare', date.today().isoformat(), {'schema': 'IUGN01-v2-etapa1'})


@permissions.guard('write')
def activate(lid):
    from db import db
    with closing(db._connect()) as conn, conn:
        client_id, _ = _work(conn, lid)
        _initialize(conn, lid, client_id)


def _audit(conn, lid, revision, key, occurred_on, detail):
    from db import db
    db._execute(conn.cursor(), '''INSERT INTO iugn_evenimente
        (lucrare_id, revision, event_key, occurred_on, recorded_at, actor, detail)
        VALUES (?, ?, ?, ?, ?, ?, ?)''',
        (int(lid), revision, key, occurred_on, datetime.now(timezone.utc).isoformat(), _actor(), _dump(detail)))


def _save(conn, lid, old_revision, state, key, day, detail):
    from db import db
    if type(old_revision) is not int or old_revision < 0:
        raise ValueError('Versiune de flux invalida.')
    cur = conn.cursor()
    db._execute(cur, '''UPDATE iugn_flux SET payload=?, revision=revision+1
        WHERE lucrare_id=? AND revision=?''', (_dump(state), int(lid), old_revision))
    if cur.rowcount != 1:
        raise WorkflowConflict('Fluxul a fost modificat in alta sesiune. Reincarca inainte sa salvezi.')
    client_id, _ = _work(conn, lid)
    _audit(conn, lid, old_revision + 1, key, day, detail)
    _sync_tasks(conn, lid, client_id, state)


def _checked_load(conn, lid, expected_revision):
    row = _load(conn, lid)
    if type(expected_revision) is not int or row['revision'] != expected_revision:
        raise WorkflowConflict('Fluxul a fost modificat in alta sesiune. Reincarca inainte sa salvezi.')
    return row['state']


def assign_roles(lid, roles, *, expected_revision):
    from db import db
    require_manager()
    if set(roles) != set(rules.ROLES) or not all(str(v).strip() for v in roles.values()):
        raise ValueError('Completeaza toate cele trei roluri.')
    with closing(db._connect()) as conn, conn:
        _work(conn, lid)
        state = _checked_load(conn, lid, expected_revision)
        if not rules.contract_ready(state):
            raise ValueError('Desemnarea se face dupa contractul semnat sau exceptia aprobata.')
        for username in roles.values():
            cur = conn.cursor()
            db._execute(cur, 'SELECT rol, activ FROM utilizatori WHERE username=?', (username,))
            row = cur.fetchone()
            if not row or not row[1] or row[0] not in {'admin', 'birou'}:
                raise ValueError('Rolurile necesita conturi active cu drept de lucru.')
        state['roles'] = dict(roles)
        _save(conn, lid, expected_revision, state, 'desemnare', date.today().isoformat(), dict(roles))
        db._execute(conn.cursor(), 'UPDATE lucrari SET responsabil=?, revision=revision+1 WHERE id=?',
                    (roles['responsabil'], int(lid)))


@permissions.guard('write')
def record_event(lid, key, occurred_on, *, expected_revision, note='', scheduled_for='', team=''):
    from db import db
    with closing(db._connect()) as conn, conn:
        record_event_in_transaction(conn, lid, key, occurred_on, expected_revision=expected_revision,
                                    note=note, scheduled_for=scheduled_for, team=team)


def record_event_in_transaction(conn, lid, key, occurred_on, *, expected_revision, note='', scheduled_for='', team=''):
    """Use the caller's transaction when issuance and workflow must commit together."""
    from db import db
    permissions.require('write')
    _work(conn, lid)
    state = _checked_load(conn, lid, expected_revision)
    if key not in rules.EVENT_LABELS:
        raise ValueError('Eveniment necunoscut.')
    if not can_record(state, key):
        raise PermissionError('Evenimentul necesita persoana desemnata pentru acest rol.')
    if key == 'contract_emis' and permissions.actor_username() is not None:
        if not contract_document_registered(conn, lid):
            raise ValueError('Contract emis se confirma automat din Documente, dupa emiterea si salvarea documentului.')
    new_state = rules.record(state, key, occurred_on, note)
    detail = {'note': str(note).strip()}
    work_fields = {}
    if key in {'executie_programata', 'programare_pif_primita'} | rules.RESCHEDULES.keys():
        target = date.fromisoformat(str(scheduled_for))
        if target < date.fromisoformat(str(occurred_on)):
            raise ValueError('Data programata nu poate preceda primirea/stabilirea programarii.')
        detail['scheduled_for'] = target.isoformat()
        field = 'data_programare' if key in {'executie_programata', 'reprogramare_executie'} else 'data_programare_pif'
        work_fields[field] = target.isoformat()
    if key in {'executie_programata', 'echipa_pif_alocata', 'reprogramare_executie'}:
        if not str(team).strip():
            raise ValueError('Echipa este obligatorie.')
        detail['team'] = str(team).strip()
        work_fields['echipa' if key in {'executie_programata', 'reprogramare_executie'} else 'echipa_pif'] = detail['team']
    if key in rules.RESCHEDULES:
        schedule = 'executie_programata' if key == 'reprogramare_executie' else 'programare_pif_primita'
        reopen = (['ordin_executie_predat'] if key == 'reprogramare_executie' else
                  ['echipa_pif_alocata', 'dosar_pif_predat', 'nota_pif_transmisa'])
        detail['previous_schedule'] = dict(state['facts'][schedule])
        detail['reopened'] = {k: new_state['facts'].pop(k) for k in reopen if k in new_state['facts']}
        new_state['facts'][schedule] = dict(new_state['facts'][schedule], scheduled_for=detail['scheduled_for'])
        if key == 'reprogramare_executie':
            new_state['facts'][schedule]['team'] = detail['team']
        else:
            work_fields['echipa_pif'] = ''
    if key in {'executie_finalizata', 'pif_efectuata'}:
        scheduled_key = 'executie_programata' if key == 'executie_finalizata' else 'programare_pif_primita'
        if str(occurred_on) < state['facts'][scheduled_key]['scheduled_for']:
            raise ValueError('Actualizeaza programarea inainte sa confirmi o finalizare anterioara ei.')
    if key == 'contract_emis':
        work_fields['data_contract'] = str(occurred_on)
    for event, status in [('oferta_acceptata', 'OFERTAT'), ('contract_emis', 'CONTRACTAT'),
                          ('executie_programata', 'PROGRAMAT'), ('executie_finalizata', 'EXECUTAT'),
                          ('pif_efectuata', 'FINALIZAT')]:
        if key == event:
            work_fields['status'] = status
    target_name = 'exceptions' if key in rules.EXCEPTIONS else 'facts'
    new_state[target_name][key].update(detail)
    _save(conn, lid, expected_revision, new_state, key, str(occurred_on), detail)
    if work_fields:
        db._execute(conn.cursor(), 'UPDATE lucrari SET ' + ', '.join(k+'=?' for k in work_fields)
                    + ', revision=revision+1 WHERE id=?', (*work_fields.values(), int(lid)))

def history(lid):
    from db import db
    with closing(db._connect()) as conn, conn:
        return db._read_frame('SELECT revision, event_key, occurred_on, recorded_at, actor, detail '
                             'FROM iugn_evenimente WHERE lucrare_id=? ORDER BY revision DESC', conn, [int(lid)])


def assignable_users():
    from db import db
    permissions.require('write')
    with closing(db._connect()) as conn, conn:
        cur = conn.cursor()
        cur.execute("SELECT username FROM utilizatori WHERE activ=1 AND rol IN ('admin','birou') ORDER BY username")
        return [row[0] for row in cur.fetchall()]


def contract_document_registered(conn, lid):
    """Check issuance evidence inside the caller's transaction."""
    from db import db
    cur = conn.cursor()
    db._execute(cur, 'SELECT number FROM iugn_contract_issues WHERE lucrare_id=?', (int(lid),))
    return cur.fetchone() is not None


def has_contract_document(lid):
    from db import db
    with closing(db._connect()) as conn:
        return contract_document_registered(conn, lid)


def correct_unlinked_contract(lid, *, expected_revision, reason):
    """Undo only an isolated, unlinked manual confirmation; preserve the audit."""
    from db import db
    require_manager()
    if not str(reason).strip():
        raise ValueError('Motivul corectiei este obligatoriu.')
    with closing(db._connect()) as conn, conn:
        if not db.DATABASE_URL:
            conn.execute('BEGIN IMMEDIATE')
        cur = conn.cursor()
        db._execute(cur, 'SELECT id FROM lucrari WHERE id=?' +
                    (' FOR UPDATE' if db.DATABASE_URL else ''), (int(lid),))
        _work(conn, lid)
        state = _checked_load(conn, lid, expected_revision)
        if contract_document_registered(conn, lid):
            raise ValueError('Exista un contract emis in dosar. Aceasta corectie nu il poate anula.')
        if 'contract_emis' not in state['facts']:
            raise ValueError('Nu exista o confirmare manuala Contract emis de corectat.')
        later = set(state['facts']) - {'oferta_acceptata', 'documente_complete', 'contract_emis'}
        if later or state['exceptions'] or any(state['roles'].values()):
            raise ValueError('Exista etape sau persoane desemnate dupa confirmare. Corectia necesita verificarea dosarului.')
        db._execute(cur, 'SELECT status,data_contract FROM lucrari WHERE id=?', (int(lid),))
        previous_work = cur.fetchone()
        previous = state['facts'].pop('contract_emis')
        detail = {'reason': str(reason).strip(), 'previous_confirmation': previous,
                  'previous_work_status': previous_work[0], 'previous_contract_date': previous_work[1]}
        _save(conn, lid, expected_revision, state, 'corectie_contract_emis',
              date.today().isoformat(), detail)
        db._execute(cur, "UPDATE lucrari SET status='OFERTAT',data_contract='',revision=revision+1 WHERE id=?",
                    (int(lid),))
    return expected_revision + 1
